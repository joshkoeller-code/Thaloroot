# Items (Items tab). Fields: name, rarity, type, coin, vp, power, text, machine
# type: treasure | light | gear | food | relic
# power: none | reusable | oneUse | hidden
# machine keys:
#   use:     one-use effects the engine applies when the item is used
#   passive: always-on bonuses while the item is held
# ---------------------------------------------------------------------------

